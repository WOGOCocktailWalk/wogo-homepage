/* ==========================================================================
   Build step for the Blog feature's templates (BUILD §21). Reads the two
   editable template files at blog/_template/post.html and
   blog/_template/index.html and embeds them into the Worker bundle as
   plain string exports — the same "hand-edited source -> generated module"
   pattern src/admin/build.mjs already uses for the admin dashboard, so a
   template edit never needs a GitHub round-trip at request time (every
   preview/publish call renders from the bundle, not a live fetch).

   Run:  node scripts/build_blog_templates.mjs   (from the backend/ directory)
   Re-run this (and redeploy) after ANY edit to blog/_template/*.html.
   ========================================================================== */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const backend = join(here, '..');
const repoRoot = join(backend, '..');

const postTemplate = readFileSync(join(repoRoot, 'blog', '_template', 'post.html'), 'utf8');
const indexTemplate = readFileSync(join(repoRoot, 'blog', '_template', 'index.html'), 'utf8');

const out = `// AUTO-GENERATED by scripts/build_blog_templates.mjs — do not edit by hand.
// Edit blog/_template/post.html / blog/_template/index.html and re-run:
//   node scripts/build_blog_templates.mjs
// (from the backend/ directory), then redeploy.

export const BLOG_POST_TEMPLATE = ${JSON.stringify(postTemplate)};
export const BLOG_INDEX_TEMPLATE = ${JSON.stringify(indexTemplate)};
`;
writeFileSync(join(backend, 'src', 'blog_templates_data.js'), out);
console.log('blog templates build ok -> src/blog_templates_data.js');
