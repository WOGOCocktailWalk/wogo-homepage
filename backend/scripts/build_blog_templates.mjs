/* ==========================================================================
   Build step for the Blog feature's templates (BUILD §21). Reads the four
   generated template files in blog/_template/generated/ (see tools/build-nl.js)
   and embeds them into the Worker bundle as
   plain string exports — the same "hand-edited source -> generated module"
   pattern src/admin/build.mjs already uses for the admin dashboard, so a
   template edit never needs a GitHub round-trip at request time (every
   preview/publish call renders from the bundle, not a live fetch).

   Run:  node scripts/build_blog_templates.mjs   (from the backend/ directory)
   Re-run this (and redeploy) after ANY edit to blog/_template/*.html.
   ========================================================================== */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const backend = join(here, '..');
const repoRoot = join(backend, '..');

// The Worker renders from the four GENERATED templates (English one-language
// pages + Dutch pages, made by `node tools/build-nl.js` at the repo root from
// the hand-edited blog/_template/post.html and index.html). Run build-nl first.
const gen = (name) => readFileSync(join(repoRoot, 'blog', '_template', 'generated', name), 'utf8');
const postEn = gen('post.en.html');
const postNl = gen('post.nl.html');
const indexEn = gen('index.en.html');
const indexNl = gen('index.nl.html');

const out = `// AUTO-GENERATED by scripts/build_blog_templates.mjs — do not edit by hand.
// Edit blog/_template/post.html / blog/_template/index.html, then from the repo
// root run  node tools/build-nl.js  and from backend/ run
//   node scripts/build_blog_templates.mjs
// and redeploy.

export const BLOG_POST_TEMPLATE = ${JSON.stringify(postEn)};
export const BLOG_POST_TEMPLATE_NL = ${JSON.stringify(postNl)};
export const BLOG_INDEX_TEMPLATE = ${JSON.stringify(indexEn)};
export const BLOG_INDEX_TEMPLATE_NL = ${JSON.stringify(indexNl)};
`;
writeFileSync(join(backend, 'src', 'blog_templates_data.js'), out);
console.log('blog templates build ok -> src/blog_templates_data.js');
