/* ==========================================================================
   Build step for the admin PWA's icons (migrations/0032 build). Reads the
   repo-root icon PNGs — icon-192.png / icon-512.png / apple-touch-icon.png,
   already built from email/logo-salmon.png for the site's own favicon/PWA
   use — and embeds them as base64 into a generated module, the same
   "hand-edited source -> generated module" pattern src/admin/build.mjs and
   scripts/build_blog_templates.mjs already use.

   WHY EMBED RATHER THAN FETCH SITE_ASSET_BASE: the simpler of the two
   options the spec allowed. Fetching from SITE_ASSET_BASE at request time
   would make the admin dashboard's "can I install this" check depend on
   GitHub Pages being up, add a cross-origin round trip to every icon
   request, and need its own caching logic to avoid re-fetching on every
   manifest read. Embedding costs ~150KB once in the Worker bundle (these
   PNGs don't change) and nothing at request time — one dependency fewer,
   consistent with how admin.css/html/js are already inlined into one
   self-contained bundle rather than fetched.

   Run:  node scripts/build_admin_icons.mjs   (from the backend/ directory)
   Re-run this (and redeploy) only if the icon source PNGs at the repo root
   ever change — they're built from email/logo-salmon.png, see ADD-A-CITY.md
   / the site's own favicon docs for how.
   ========================================================================== */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const backend = join(here, '..');
const repoRoot = join(backend, '..');

const icon192 = readFileSync(join(repoRoot, 'icon-192.png')).toString('base64');
const icon512 = readFileSync(join(repoRoot, 'icon-512.png')).toString('base64');
const appleTouchIcon = readFileSync(join(repoRoot, 'apple-touch-icon.png')).toString('base64');

const out = `// AUTO-GENERATED by scripts/build_admin_icons.mjs — do not edit by hand.
// Base64 of the repo-root icon-192.png / icon-512.png / apple-touch-icon.png
// (the real WOGO mark, built from email/logo-salmon.png). Re-run
// scripts/build_admin_icons.mjs (then redeploy) only if those source PNGs
// change — see that script's own doc comment for why they're embedded
// rather than fetched from SITE_ASSET_BASE at request time.

export const ADMIN_ICON_192_B64 = ${JSON.stringify(icon192)};
export const ADMIN_ICON_512_B64 = ${JSON.stringify(icon512)};
export const ADMIN_APPLE_TOUCH_ICON_B64 = ${JSON.stringify(appleTouchIcon)};
`;
writeFileSync(join(backend, 'src', 'admin', 'icons_data.js'), out);
console.log('admin icons build ok -> src/admin/icons_data.js');
